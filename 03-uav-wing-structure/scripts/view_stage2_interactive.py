"""
Interactive viewer (PyVista window via WSLg) for the Stage 2 results,
2.0mm mesh. Rotating by hand is inherently interactive; the scene is
still generated by this script from the solver output.

Usage (conda env ccx223):
  python3 scripts/view_stage2_interactive.py uy   # displacement contour (default)
  python3 scripts/view_stage2_interactive.py vm   # von Mises contour

Mouse: left-drag rotate, scroll/right-drag zoom, middle-drag pan, 'q' quit.
Slider: deformation exaggeration (0 = undeformed).
Requires simulation/stage2_ribs_h2p0_fields.vtu (written by
scripts/render_stage2_contours.py).
"""
import sys
import numpy as np
import pyvista as pv

VTU = "simulation/stage2_ribs_h2p0_fields.vtu"
mode = sys.argv[1] if len(sys.argv) > 1 else "uy"
if mode not in ("uy", "vm"):
    print("Usage: view_stage2_interactive.py [uy|vm]")
    sys.exit(1)

grid = pv.read(VTU)
surf = grid.extract_surface(algorithm="dataset_surface")
base = np.array(surf.points)
U = np.array(surf.point_data["U"])
mesh = surf.copy(deep=True)

if mode == "uy":
    uy = np.array(surf.point_data["Uy_mm"])
    scalars, title = "Uy_mm", "Uy [mm]"
    clim = (float(uy.min()), float(uy.max()))
    caption = ("Stage 2 (spar + 6 ribs), 2.0mm mesh: Uy\n"
               "colorbar max = leading edge of tip rib (twist); spar-axis tip Uy = 3.679 mm")
    init_scale = 50.0
else:
    vm = np.array(surf.point_data["von_Mises_MPa"])
    p99 = float(np.percentile(vm, 99.0))
    scalars, title = "von_Mises_MPa", "von Mises [MPa]"
    clim = (0.0, p99)
    caption = (f"Stage 2 (spar + 6 ribs), 2.0mm mesh: von Mises\n"
               f"scale capped at 99th pct ({p99:.1f} MPa); peak {vm.max():.1f} MPa "
               f"is a local, unconverged corner value")
    init_scale = 0.0

mesh.points = base + init_scale * U

pl = pv.Plotter(window_size=(1400, 900))
pl.add_mesh(mesh, scalars=scalars, cmap="turbo", clim=clim,
            scalar_bar_args={"title": title, "vertical": True,
                             "n_labels": 6, "fmt": "%.2f"})
pl.add_text(caption, font_size=9, position="upper_left")
pl.add_axes()


def set_scale(value):
    mesh.points = base + float(value) * U
    pl.render()


pl.add_slider_widget(set_scale, [0.0, 200.0], value=init_scale,
                     title="Deformation exaggeration (x)",
                     pointa=(0.25, 0.06), pointb=(0.75, 0.06))
pl.camera_position = "iso"
pl.show()
