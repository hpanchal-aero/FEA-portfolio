#!/usr/bin/python3
"""Imperfect copy of a panel mesh: every node is shifted in z by A sin(pi x/L) sin(pi y/L) (Project 05, V7).

Usage: /usr/bin/python3 scripts/make_imperfect_mesh.py BASE_TAG OUT_TAG --a_over_h 0.1
Reads mesh/BASE_TAG.inp, writes mesh/OUT_TAG.inp. Only the z coordinate of the *NODE data lines changes; elements, sets and
the x, y text are copied unchanged. The shape is the first buckling mode of the simply supported plate (the finite-element
mode of V6 has this shape, R^2 = 1.00000). Edge nodes (x or y on the plate boundary) are not moved, so the node sets and the
frame equations of BASE_TAG stay valid. A = a_over_h * h, h = plate thickness read from the nodes.
Checks after writing: maximum shift equals A, no edge node moved, x and y unchanged, thickness along every vertical line
unchanged (all nodes at the same (x, y) shift equally), node count unchanged.
"""
import argparse
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import ccxio

EPS = 1e-12


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("base")
    ap.add_argument("out")
    ap.add_argument("--a_over_h", type=float, required=True)
    args = ap.parse_args()
    root = os.path.dirname(HERE)
    base_path = os.path.join(root, "mesh", args.base + ".inp")
    out_path = os.path.join(root, "mesh", args.out + ".inp")
    if not os.path.exists(base_path):
        raise SystemExit("missing %s" % base_path)
    nodes = ccxio.read_nodes(base_path)
    xs = [nodes[k][0] for k in nodes]
    ys = [nodes[k][1] for k in nodes]
    zs = [nodes[k][2] for k in nodes]
    xmin, xmax, ymin, ymax = min(xs), max(xs), min(ys), max(ys)
    Lx, Ly = xmax - xmin, ymax - ymin
    h = max(zs) - min(zs)
    amp = args.a_over_h * h

    def shift(x, y):
        if x < xmin + EPS or x > xmax - EPS or y < ymin + EPS or y > ymax - EPS:
            return 0.0
        return amp * math.sin(math.pi * (x - xmin) / Lx) * math.sin(math.pi * (y - ymin) / Ly)

    with open(base_path) as f:
        lines = f.read().splitlines()
    out = ["** imperfect mesh generated by scripts/make_imperfect_mesh.py from %s: z shifted by A sin(pi x/L) sin(pi y/L), A = %g h = %.6e m" % (args.base, args.a_over_h, amp)]
    in_node = False
    nmod = 0
    nlines = 0
    for s in lines:
        t = s.strip().upper()
        if t.startswith("*"):
            in_node = t.startswith("*NODE") and not t.startswith("*NODE PRINT") and not t.startswith("*NODE FILE") and not t.startswith("*NODE OUTPUT")
            out.append(s)
            continue
        if in_node and t and not t.startswith("**"):
            p = s.split(",")
            if len(p) != 4:
                raise SystemExit("unexpected node line: %r" % s)
            x, y, z = float(p[1]), float(p[2]), float(p[3])
            dz = shift(x, y)
            if dz != 0.0:
                nmod += 1
            out.append("%s,%s,%s, %.12e" % (p[0], p[1], p[2], z + dz))
            nlines += 1
        else:
            out.append(s)
    if nlines != len(nodes):
        raise SystemExit("rewrote %d node lines but the mesh has %d nodes" % (nlines, len(nodes)))
    with open(out_path, "w") as f:
        f.write("\n".join(out) + "\n")

    new = ccxio.read_nodes(out_path)
    if len(new) != len(nodes):
        raise SystemExit("node count changed")
    maxdz = 0.0
    edge_moved = 0
    col = {}
    for k in nodes:
        x, y, z = nodes[k]
        x2, y2, z2 = new[k]
        if abs(x2 - x) > 1e-15 or abs(y2 - y) > 1e-15:
            raise SystemExit("x or y changed for node %d" % k)
        dz = z2 - z
        maxdz = max(maxdz, abs(dz))
        if (x < xmin + EPS or x > xmax - EPS or y < ymin + EPS or y > ymax - EPS) and abs(dz) > 0:
            edge_moved += 1
        key = (round(x, 9), round(y, 9))
        col.setdefault(key, []).append(dz)
    spread = max(max(v) - min(v) for v in col.values())
    print("base %s -> %s: %d nodes, plate %.3f x %.3f x %.4f m" % (args.base, args.out, len(nodes), Lx, Ly, h))
    print("imperfection A = %g h = %.6e m; nodes shifted %d; edge nodes moved %d" % (args.a_over_h, amp, nmod, edge_moved))
    print("max |dz| = %.9e m (A = %.9e m); max dz difference along a vertical line = %.2e m" % (maxdz, amp, spread))
    if edge_moved or abs(maxdz - abs(amp)) > 1e-9 * max(abs(amp), 1.0) * 1e3 or spread > 1e-15:
        raise SystemExit("CHECK FAILED")
    print("wrote %s; line count %d (base %d)" % (os.path.relpath(out_path, root), len(out), len(lines)))


if __name__ == "__main__":
    main()
